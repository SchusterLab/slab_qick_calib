class PumpedResSpecProgram(ResSpecProgram):
    """ResSpec with an additional periodic pump tone on a QICK generator."""

    def _initialize(self, cfg):
        cfg = AttrDict(self.cfg)
        pump_ch = int(cfg.expt.pump_ch)

        gen_args = {"ch": pump_ch, "nqz": int(cfg.expt.pump_nqz)}
        if self.soccfg["gens"][pump_ch].get("has_mixer", False):
            gen_args["mixer_freq"] = float(cfg.expt.pump_mixer_freq)
        self.declare_gen(**gen_args)
        self.add_pulse(
            ch=pump_ch,
            name="jpa_pump",
            style="const",
            freq=float(cfg.expt.pump_freq),
            phase=float(cfg.expt.get("pump_phase", 0.0)),
            gain=float(cfg.expt.pump_gain),
            length=float(cfg.expt.get("pump_length", 1.0)),
            mode="periodic",
        )

        super()._initialize(cfg)

    def _body(self, cfg):
        cfg = AttrDict(self.cfg)
        self.pulse(ch=int(cfg.expt.pump_ch), name="jpa_pump", t=0)
        if cfg.expt.get("pump_settle_us", 0.0) > 0:
            self.delay(t=float(cfg.expt.pump_settle_us), tag="wait_jpa_pump")
        super()._body(cfg)


class PumpedResSpec(ResSpec):
    """ResSpec wrapper that uses PumpedResSpecProgram."""

    def acquire(self, progress=False):
        q = self.cfg.expt.qubit[0]
        self.cfg.device.readout.final_delay[q] = self.cfg.expt.final_delay
        self.param = {"label": "readout_pulse", "param": "freq", "param_type": "pulse"}

        if self.cfg.expt.loop:
            raise NotImplementedError("PumpedResSpec currently supports hardware frequency sweeps only.")

        self.cfg.expt.frequency = QickSweep1D(
            "freq_loop",
            self.cfg.expt.start,
            self.cfg.expt.start + self.cfg.expt.span,
        )
        QickExperiment.acquire(self, PumpedResSpecProgram, progress=progress)
        return self.data


class JPAFineTuning(QickExperiment):
    """
    Measure the waste baseline, then scan JPA pump gain versus DC bias.

    The pump is generated by the RFSoC/QICK generator during each waste
    resonator spectroscopy shot. The reported gain map is the measured
    amplitude gain near the waste resonance relative to the baseline.
    """

    def __init__(
        self,
        cfg_dict,
        prefix="",
        progress=True,
        display=True,
        save=True,
        analyze=True,
        qi=1,
        go=True,
        params=None,
        style="fine",
        check_params=True,
    ):
        if params is None:
            params = {}
        if not prefix:
            prefix = f"jpa_fine_tuning_qubit{qi}"

        super().__init__(
            cfg_dict=cfg_dict,
            prefix=prefix,
            progress=progress,
            qi=qi,
            check_params=check_params,
        )
        self.cfg_dict = cfg_dict
        self.qi = qi

        waste_mhz = float(params.get("waste_freq_mhz", self.cfg.device.readout.frequency[qi]))
        pump_freq_mhz = float(params.get("pump_freq_mhz", waste_mhz + params.get("pump_detuning_mhz", 2.0)))
        pump_if_mhz = float(params.get("pump_if_mhz", 400.0))

        inner_defaults = {
            "qubit": [qi],
            "center": waste_mhz,
            "span": 5.0,
            "expts": 220,
            "length": self.cfg.device.readout.readout_length[qi],
            "gain": self.cfg.device.readout.gain[qi],
            "reps": self.reps,
            "rounds": self.rounds,
            "final_delay": 5,
            "pulse_e": False,
            "pulse_f": False,
            "long_pulse": False,
            "loop": False,
            "phase_const": False,
            "active_reset": False,
            "flux": False,
        }
        jpa_defaults = {
            "waste_freq_mhz": waste_mhz,
            "gain_window_mhz": 0.25,
            "pump_ch": 13,
            "pump_nqz": 2,
            "pump_type": "int",
            "pump_freq": pump_freq_mhz,
            "pump_freq_mhz": pump_freq_mhz,
            "pump_mixer_freq": pump_freq_mhz - pump_if_mhz,
            "pump_mixer_freq_mhz": pump_freq_mhz - pump_if_mhz,
            "pump_if_mhz": pump_if_mhz,
            "pump_phase": 0.0,
            "pump_length": 1.0,
            "pump_settle_us": 0.2,
            "pump_gains": np.linspace(0.002, 0.03, 15),
            "dc_biases_v": np.linspace(112e-3, 122e-3, 21),
            "bias_chan": self.cfg.hw.soc.dacs.flux.dc_ch[qi],
            "dc_settle": 0.25,
            "off_bias": 0.0,
            "baseline_pump_gain": 0.0,
            "reset_bias_after": True,
            "pump_on_after": True,
            "configure_pump_rf": True,
            "pump_filter_type": "bandpass",
            "pump_filter_bw_mhz": 1000.0,
            "pump_attn1_db": 15.0,
            "pump_attn2_db": 0.0,
            "dc_verify_print": False,
            "rspec_update": False,
            "update": False,
            "rspec_update_verbose": True,
            "show_baseline": True,
            "live_heatmap": True,
        }

        p = {**inner_defaults, **jpa_defaults, **params}
        p["pump_freq"] = float(p.get("pump_freq_mhz", p["pump_freq"]))
        p["pump_freq_mhz"] = float(p["pump_freq"])
        if "pump_mixer_freq_mhz" in p:
            p["pump_mixer_freq"] = float(p["pump_mixer_freq_mhz"])
        p["pump_mixer_freq_mhz"] = float(p["pump_mixer_freq"])
        p["start"] = p["center"] - p["span"] / 2.0 if "center" in p else p["start"]

        self.cfg.expt = AttrDict(p)
        self.xlabel = "Waste Readout Frequency (MHz)"
        self.ylabel = "JPA DC Bias (mV)"

        if go:
            self.run(progress=progress, analyze=analyze, display=display, save=save)

    def _configure_pump_rf(self, soc):
        if not self.cfg.expt.configure_pump_rf:
            return

        pump_ch = int(self.cfg.expt.pump_ch)
        fc_ghz = float(self.cfg.expt.pump_freq) / 1000.0
        bw_ghz = float(self.cfg.expt.pump_filter_bw_mhz) / 1000.0
        ftype = self.cfg.expt.pump_filter_type

        if hasattr(soc, "rfb_set_gen_filter"):
            try:
                soc.rfb_set_gen_filter(pump_ch, fc=fc_ghz, bw=bw_ghz, ftype=ftype)
            except TypeError:
                soc.rfb_set_gen_filter(pump_ch, fc=fc_ghz, ftype=ftype)
        elif hasattr(soc, "rfb_set_dac_filter"):
            try:
                soc.rfb_set_dac_filter(dac_port=pump_ch, fc=fc_ghz, bw=bw_ghz, ftype=ftype)
            except TypeError:
                soc.rfb_set_dac_filter(dac_port=pump_ch, fc=fc_ghz, ftype=ftype)

        if hasattr(soc, "rfb_set_gen_rf"):
            soc.rfb_set_gen_rf(
                pump_ch,
                float(self.cfg.expt.pump_attn1_db),
                float(self.cfg.expt.pump_attn2_db),
            )

    def _res_params(self, pump_gain):
        p = dict(self.cfg.expt)
        for key in (
            "dc_biases_v",
            "bias_chan",
            "dc_settle",
            "off_bias",
            "baseline_pump_gain",
            "reset_bias_after",
            "pump_on_after",
            "configure_pump_rf",
            "pump_filter_type",
            "pump_filter_bw_mhz",
            "pump_attn1_db",
            "pump_attn2_db",
            "dc_verify_print",
            "gain_window_mhz",
            "rspec_update",
            "update",
            "rspec_update_verbose",
            "show_baseline",
            "live_heatmap",
        ):
            p.pop(key, None)
        p["pump_gain"] = float(pump_gain)
        p["start"] = p["center"] - p["span"] / 2.0 if "center" in p else p["start"]
        return p

    def _turn_on_best_pump(self, pump_gain, dc_bias_v):
        soc = self.im[self.cfg.aliases.soc]
        bias_chan = int(self.cfg.expt.bias_chan)

        soc.rfb_set_bias(bias_chan, float(dc_bias_v))
        if self.cfg.expt.dc_settle > 0:
            time.sleep(float(self.cfg.expt.dc_settle))

        set_periodic_tone(
            soc,
            self.soccfg,
            ch=int(self.cfg.expt.pump_ch),
            freq_mhz=float(self.cfg.expt.pump_freq),
            gain=float(pump_gain),
            nqz=int(self.cfg.expt.pump_nqz),
            mixer_freq_mhz=float(self.cfg.expt.pump_mixer_freq),
        )
        print(
            f"JPA parked at best point: bias={1e3 * float(dc_bias_v):.3f} mV, "
            f"pump gain={float(pump_gain):.5f}"
        )

    def _plot_baseline(self, freq, baseline_db):
        fig, ax = plt.subplots(figsize=(7, 4))
        ax.plot(freq, baseline_db)
        ax.axvline(float(self.cfg.expt.waste_freq_mhz), color="k", lw=1)
        ax.set_xlabel("Frequency (MHz)")
        ax.set_ylabel("JPA-off response (dB)")
        ax.set_title("Waste baseline with JPA off")
        ax.grid(True)
        fig.tight_layout()
        plt.show()

    def _plot_live_heatmap(self, freq, baseline_db, pump_gains, dc_biases, gain_at_waste_db,
                            current_db=None, current_pump_gain=None, current_dc_bias=None):
        try:
            from IPython.display import clear_output
            clear_output(wait=True)
        except Exception:
            pass

        fig, ax = plt.subplots(2, 1, figsize=(7, 8), sharex=False)
        ax[0].plot(freq, baseline_db, label="JPA off (baseline)")
        if current_db is not None:
            label = "JPA on"
            if current_pump_gain is not None and current_dc_bias is not None:
                label = f"JPA on (gain {current_pump_gain:.5f}, bias {1e3*current_dc_bias:.3f} mV)"
            ax[0].plot(freq, current_db, label=label)
        ax[0].axvline(float(self.cfg.expt.waste_freq_mhz), color="k", lw=1)
        ax[0].set_xlabel("Frequency (MHz)")
        ax[0].set_ylabel("Response (dB)")
        ax[0].set_title("Waste baseline vs current scan")
        ax[0].legend()
        ax[0].grid(True)

        mesh = ax[1].pcolormesh(
            1e3 * dc_biases,
            pump_gains,
            gain_at_waste_db,
            shading="auto",
        )
        ax[1].set_xlabel("JPA DC bias (mV)")
        ax[1].set_ylabel("Pump gain (DAC units)")
        ax[1].set_title(f"Gain near {float(self.cfg.expt.waste_freq_mhz):.3f} MHz")
        fig.colorbar(mesh, ax=ax[1], label="Gain vs baseline (dB)")
        fig.tight_layout()
        plt.show()

    def _run_pumped_res_spec(self, pump_gain, dc_bias):
        params = self._res_params(pump_gain)
        params["jpa_dc_bias"] = float(dc_bias)
        exp = PumpedResSpec(
            self.cfg_dict,
            qi=self.qi,
            go=False,
            params=params,
            style="fine",
            check_params=False,
        )
        return exp.acquire(progress=False)

    def acquire(self, progress=False):
        try:
            from tqdm import tqdm
        except Exception:
            tqdm = lambda x, disable=False: x

        soc = self.im[self.cfg.aliases.soc]
        bias_chan = int(self.cfg.expt.bias_chan)
        pump_gains = np.asarray(self.cfg.expt.pump_gains, dtype=float)
        dc_biases = np.asarray(self.cfg.expt.dc_biases_v, dtype=float)

        self._configure_pump_rf(soc)

        try:
            soc.rfb_set_bias(bias_chan, float(self.cfg.expt.off_bias))
            if self.cfg.expt.dc_settle > 0:
                time.sleep(float(self.cfg.expt.dc_settle))
            baseline = self._run_pumped_res_spec(
                float(self.cfg.expt.baseline_pump_gain),
                float(self.cfg.expt.off_bias),
            )

            freq = np.asarray(baseline["xpts"])
            baseline_amps = np.asarray(baseline["amps"])
            baseline_db = 20 * np.log10(np.maximum(baseline_amps, 1e-12))
            gain_mask = np.abs(freq - float(self.cfg.expt.waste_freq_mhz)) <= float(self.cfg.expt.gain_window_mhz)
            if not np.any(gain_mask):
                gain_mask = np.ones_like(freq, dtype=bool)

            if self.cfg.expt.show_baseline:
                self._plot_baseline(freq, baseline_db)

            scan_amps = np.full((len(pump_gains), len(dc_biases), len(freq)), np.nan)
            scan_phases = np.full_like(scan_amps, np.nan)
            scan_avgi = np.full_like(scan_amps, np.nan)
            scan_avgq = np.full_like(scan_amps, np.nan)
            gain_db = np.full_like(scan_amps, np.nan)
            gain_at_waste_db = np.full((len(pump_gains), len(dc_biases)), np.nan)
            dc_readback_v = np.full_like(gain_at_waste_db, np.nan)
            times = np.full_like(gain_at_waste_db, np.nan)

            for i, pump_gain in enumerate(tqdm(pump_gains, disable=not progress)):
                for j, dc_bias in enumerate(dc_biases):
                    soc.rfb_set_bias(bias_chan, float(dc_bias))
                    if self.cfg.expt.dc_settle > 0:
                        time.sleep(float(self.cfg.expt.dc_settle))

                    rb = np.nan
                    try:
                        rb = float(soc.rfb_get_bias(bias_chan))
                    except Exception:
                        pass
                    if self.cfg.expt.dc_verify_print:
                        print(
                            f"[JPA fine] pump gain {pump_gain:.5f}, "
                            f"bias set {dc_bias*1e3:.3f} mV, read {rb*1e3:.3f} mV"
                        )

                    row = self._run_pumped_res_spec(pump_gain, dc_bias)
                    row_amps = np.asarray(row["amps"])
                    row_db = 20 * np.log10(np.maximum(row_amps, 1e-12))

                    scan_amps[i, j] = row_amps
                    scan_phases[i, j] = row["phases"]
                    scan_avgi[i, j] = row["avgi"]
                    scan_avgq[i, j] = row["avgq"]
                    gain_db[i, j] = row_db - baseline_db
                    gain_at_waste_db[i, j] = np.nanmean(gain_db[i, j, gain_mask])
                    dc_readback_v[i, j] = rb
                    times[i, j] = time.time()

                    if self.cfg.expt.live_heatmap:
                        self._plot_live_heatmap(
                            freq,
                            baseline_db,
                            pump_gains,
                            dc_biases,
                            gain_at_waste_db,
                            current_db=row_db,
                            current_pump_gain=pump_gain,
                            current_dc_bias=dc_bias,
                        )
        finally:
            if self.cfg.expt.reset_bias_after:
                soc.rfb_set_bias(bias_chan, float(self.cfg.expt.off_bias))

        data = {
            "freq_mhz": freq,
            "xpts": freq,
            "baseline": copy.deepcopy(baseline),
            "baseline_amps": baseline_amps,
            "baseline_db": baseline_db,
            "pump_gains": pump_gains,
            "dc_biases_v": dc_biases,
            "dc_biases_mv": 1e3 * dc_biases,
            "dc_readback_v": dc_readback_v,
            "scan_amps": scan_amps,
            "scan_phases": scan_phases,
            "scan_avgi": scan_avgi,
            "scan_avgq": scan_avgq,
            "gain_db": gain_db,
            "gain_at_waste_db": gain_at_waste_db,
            "gain_window_mhz": float(self.cfg.expt.gain_window_mhz),
            "waste_freq_mhz": float(self.cfg.expt.waste_freq_mhz),
            "pump_freq_mhz": float(self.cfg.expt.pump_freq),
            "pump_mixer_freq_mhz": float(self.cfg.expt.pump_mixer_freq),
            "pump_ch": int(self.cfg.expt.pump_ch),
            "pump_attn1_db": float(self.cfg.expt.pump_attn1_db),
            "pump_attn2_db": float(self.cfg.expt.pump_attn2_db),
            "time": times,
        }
        self.data = data
        return data

    def analyze(self, data=None, **kwargs):
        if data is None:
            data = self.data

        ind = np.unravel_index(np.nanargmax(data["gain_at_waste_db"]), data["gain_at_waste_db"].shape)
        data["best_pump_gain"] = float(data["pump_gains"][ind[0]])
        data["best_dc_bias_v"] = float(data["dc_biases_v"][ind[1]])
        data["best_dc_bias_mv"] = 1e3 * data["best_dc_bias_v"]
        data["best_gain_db"] = float(data["gain_at_waste_db"][ind])
        data["best_index"] = np.asarray(ind)
        self.data = data
        if self.cfg.expt.pump_on_after:
            self._turn_on_best_pump(data["best_pump_gain"], data["best_dc_bias_v"])
        if should_update_yaml(self.cfg.expt):
            update_jpa_config(
                self.config_file,
                self.cfg.expt,
                data=data,
                verbose=bool(self.cfg.expt.rspec_update_verbose),
            )
        return data

    def display(self, data=None, **kwargs):
        if data is None:
            data = self.data

        fig, ax = plt.subplots(figsize=(7, 4.5))
        mesh = ax.pcolormesh(
            data["dc_biases_mv"],
            data["pump_gains"],
            data["gain_at_waste_db"],
            shading="auto",
        )
        ax.set_xlabel("JPA DC Bias (mV)")
        ax.set_ylabel("Pump DAC Gain")
        ax.set_title(
            f"JPA Fine Tuning: gain near {data['waste_freq_mhz']:.3f} MHz"
        )
        fig.colorbar(mesh, ax=ax, label="Gain vs baseline (dB)")

        if "best_gain_db" in data:
            ax.plot(data["best_dc_bias_mv"], data["best_pump_gain"], "wo", ms=7, mec="k")
            ax.text(
                data["best_dc_bias_mv"],
                data["best_pump_gain"],
                f"  {data['best_gain_db']:.1f} dB",
                color="white",
                va="center",
            )

        fig.tight_layout()
        plt.show()
        return fig, ax


class JPAAdaptiveFineTuning(JPAFineTuning):
    """
    Live adaptive JPA tuning over bounded pump-gain and DC-bias ranges.

    The scan starts with a coarse grid over the full range, then repeatedly
    measures smaller local grids around the best point. Each cycle starts with
    the full coarse grid again, which lets the tracker follow a drifting/noisy
    JPA optimum instead of locking onto yesterday's best point.
    """

    def _res_params(self, pump_gain):
        p = super()._res_params(pump_gain)
        for key in (
            "pump_range",
            "dc_range",
            "adaptive_stage_grids",
            "adaptive_shrink",
            "adaptive_cycles",
            "adaptive_full_rescan_each_cycle",
            "adaptive_live",
        ):
            p.pop(key, None)
        return p

    def _bounds_from_center(self, center, half_width, full_range):
        lo = max(float(full_range[0]), float(center) - float(half_width))
        hi = min(float(full_range[1]), float(center) + float(half_width))
        if lo == hi:
            lo, hi = float(full_range[0]), float(full_range[1])
        return lo, hi

    def _make_heatmap_from_history(self, pump_pts, dc_pts, gains):
        pumps = np.unique(np.asarray(pump_pts, dtype=float))
        dcs = np.unique(np.asarray(dc_pts, dtype=float))
        z = np.full((len(pumps), len(dcs)), np.nan)

        for i, pump in enumerate(pumps):
            for j, dc in enumerate(dcs):
                mask = (np.asarray(pump_pts) == pump) & (np.asarray(dc_pts) == dc)
                if np.any(mask):
                    z[i, j] = np.nanmean(np.asarray(gains)[mask])
        return pumps, dcs, z

    def _plot_adaptive_live(
        self,
        freq,
        baseline_db,
        pump_pts,
        dc_pts,
        gains,
        cycle_pts,
        stage_pts,
        current_cycle,
        stage_grids,
        best,
    ):
        try:
            from IPython.display import clear_output
            clear_output(wait=True)
        except Exception:
            pass

        nstages = len(stage_grids)
        fig, ax = plt.subplots(nstages + 1, 1, figsize=(7, 3.0 + 3.0 * nstages), sharex=False)
        if nstages == 0:
            ax = [ax]

        ax[0].plot(freq, baseline_db)
        ax[0].axvline(float(self.cfg.expt.waste_freq_mhz), color="k", lw=1)
        ax[0].set_xlabel("Frequency (MHz)")
        ax[0].set_ylabel("JPA-off response (dB)")
        ax[0].set_title("Waste baseline")
        ax[0].grid(True)

        gain_arr = np.asarray(gains, dtype=float)
        cycle_arr = np.asarray(cycle_pts, dtype=int)
        stage_arr = np.asarray(stage_pts, dtype=int)
        pump_arr = np.asarray(pump_pts, dtype=float)
        dc_arr = np.asarray(dc_pts, dtype=float)
        current_mask = cycle_arr == int(current_cycle)
        finite_current = gain_arr[current_mask & np.isfinite(gain_arr)]
        vmin = np.nanmin(finite_current) if finite_current.size else None
        vmax = np.nanmax(finite_current) if finite_current.size else None

        for stage, grid in enumerate(stage_grids):
            stage_ax = ax[stage + 1]
            mask = current_mask & (stage_arr == stage)
            stage_ax.set_xlabel("JPA DC bias (mV)")
            stage_ax.set_ylabel("Pump gain")
            stage_ax.set_title(
                f"Cycle {current_cycle}, stage {stage + 1}: {int(grid[0])}x{int(grid[1])}"
            )

            if not np.any(mask):
                stage_ax.text(0.5, 0.5, "waiting for this grid", ha="center", va="center",
                              transform=stage_ax.transAxes)
                continue

            pumps, dcs, z = self._make_heatmap_from_history(
                pump_arr[mask],
                dc_arr[mask],
                gain_arr[mask],
            )
            mesh = stage_ax.pcolormesh(
                1e3 * dcs,
                pumps,
                z,
                shading="auto",
                vmin=vmin,
                vmax=vmax,
            )
            stage_ax.scatter(
                1e3 * dc_arr[mask],
                pump_arr[mask],
                c="w",
                s=18,
                edgecolors="k",
                linewidths=0.35,
            )
            if best is not None:
                stage_ax.plot(1e3 * best["dc_bias_v"], best["pump_gain"], "rx", ms=9, mew=2)
            fig.colorbar(mesh, ax=stage_ax, label="Gain vs baseline (dB)")

        fig.tight_layout()
        plt.show()

    def acquire(self, progress=False):
        try:
            from tqdm import tqdm
        except Exception:
            tqdm = lambda x, disable=False: x

        soc = self.im[self.cfg.aliases.soc]
        bias_chan = int(self.cfg.expt.bias_chan)

        default_pump_range = (
            float(np.nanmin(self.cfg.expt.pump_gains)),
            float(np.nanmax(self.cfg.expt.pump_gains)),
        )
        default_dc_range = (
            float(np.nanmin(self.cfg.expt.dc_biases_v)),
            float(np.nanmax(self.cfg.expt.dc_biases_v)),
        )
        pump_range = tuple(self.cfg.expt.get("pump_range", default_pump_range))
        pump_gain_max = float(self.cfg.expt.get("pump_gain_max", 1.0))
        pump_range = (
            max(0.0, min(float(pump_range[0]), pump_gain_max)),
            max(0.0, min(float(pump_range[1]), pump_gain_max)),
        )
        if pump_range[0] > pump_range[1]:
            pump_range = (pump_range[1], pump_range[0])
        dc_range = tuple(self.cfg.expt.get("dc_range", default_dc_range))
        stage_grids = list(self.cfg.expt.get("adaptive_stage_grids", [(5, 5), (3, 3), (3, 3)]))
        adaptive_shrink = float(self.cfg.expt.get("adaptive_shrink", 0.5))
        cycles = int(self.cfg.expt.get("adaptive_cycles", 1))
        full_rescan_each_cycle = bool(self.cfg.expt.get("adaptive_full_rescan_each_cycle", True))
        adaptive_live = bool(self.cfg.expt.get("adaptive_live", True))

        self._configure_pump_rf(soc)

        pump_pts = []
        dc_pts = []
        gain_pts = []
        cycle_pts = []
        stage_pts = []
        trace_gain_db = []
        trace_amps = []
        trace_phases = []
        dc_readback_v = []
        times = []
        best = None

        try:
            soc.rfb_set_bias(bias_chan, float(self.cfg.expt.off_bias))
            if self.cfg.expt.dc_settle > 0:
                time.sleep(float(self.cfg.expt.dc_settle))
            baseline = self._run_pumped_res_spec(
                float(self.cfg.expt.baseline_pump_gain),
                float(self.cfg.expt.off_bias),
            )

            freq = np.asarray(baseline["xpts"])
            baseline_amps = np.asarray(baseline["amps"])
            baseline_db = 20 * np.log10(np.maximum(baseline_amps, 1e-12))
            gain_mask = np.abs(freq - float(self.cfg.expt.waste_freq_mhz)) <= float(self.cfg.expt.gain_window_mhz)
            if not np.any(gain_mask):
                gain_mask = np.ones_like(freq, dtype=bool)

            if self.cfg.expt.show_baseline:
                self._plot_baseline(freq, baseline_db)

            cycle_iter = tqdm(range(cycles), disable=not progress)
            for cycle in cycle_iter:
                center_pump = 0.5 * (pump_range[0] + pump_range[1]) if best is None else best["pump_gain"]
                center_dc = 0.5 * (dc_range[0] + dc_range[1]) if best is None else best["dc_bias_v"]
                pump_bounds = pump_range
                dc_bounds = dc_range

                for stage, (n_pump, n_dc) in enumerate(stage_grids):
                    use_full = stage == 0 and (cycle == 0 or full_rescan_each_cycle)
                    if use_full:
                        pump_bounds = pump_range
                        dc_bounds = dc_range
                    elif stage == 0:
                        pump_bounds = self._bounds_from_center(center_pump, pump_halfwidth, pump_range)
                        dc_bounds = self._bounds_from_center(center_dc, dc_halfwidth, dc_range)

                    pump_grid = np.linspace(pump_bounds[0], pump_bounds[1], int(n_pump))
                    dc_grid = np.linspace(dc_bounds[0], dc_bounds[1], int(n_dc))
                    pump_step = abs(pump_grid[1] - pump_grid[0]) if len(pump_grid) > 1 else abs(pump_bounds[1] - pump_bounds[0])
                    dc_step = abs(dc_grid[1] - dc_grid[0]) if len(dc_grid) > 1 else abs(dc_bounds[1] - dc_bounds[0])

                    for pump_gain in pump_grid:
                        for dc_bias in dc_grid:
                            soc.rfb_set_bias(bias_chan, float(dc_bias))
                            if self.cfg.expt.dc_settle > 0:
                                time.sleep(float(self.cfg.expt.dc_settle))

                            rb = np.nan
                            try:
                                rb = float(soc.rfb_get_bias(bias_chan))
                            except Exception:
                                pass

                            row = self._run_pumped_res_spec(float(pump_gain), float(dc_bias))
                            row_amps = np.asarray(row["amps"])
                            row_db = 20 * np.log10(np.maximum(row_amps, 1e-12))
                            row_gain_db = row_db - baseline_db
                            gain_at_waste = float(np.nanmean(row_gain_db[gain_mask]))

                            pump_pts.append(float(pump_gain))
                            dc_pts.append(float(dc_bias))
                            gain_pts.append(gain_at_waste)
                            cycle_pts.append(cycle)
                            stage_pts.append(stage)
                            trace_gain_db.append(row_gain_db)
                            trace_amps.append(row_amps)
                            trace_phases.append(np.asarray(row["phases"]))
                            dc_readback_v.append(rb)
                            times.append(time.time())

                            if best is None or gain_at_waste > best["gain_db"]:
                                best = {
                                    "gain_db": gain_at_waste,
                                    "pump_gain": float(pump_gain),
                                    "dc_bias_v": float(dc_bias),
                                }
                                center_pump = best["pump_gain"]
                                center_dc = best["dc_bias_v"]

                            if adaptive_live:
                                self._plot_adaptive_live(
                                    freq,
                                    baseline_db,
                                    pump_pts,
                                    dc_pts,
                                    gain_pts,
                                    cycle_pts,
                                    stage_pts,
                                    cycle,
                                    stage_grids,
                                    best,
                                )

                    pump_halfwidth = pump_step * adaptive_shrink
                    dc_halfwidth = dc_step * adaptive_shrink
                    pump_bounds = self._bounds_from_center(center_pump, pump_halfwidth, pump_range)
                    dc_bounds = self._bounds_from_center(center_dc, dc_halfwidth, dc_range)
        finally:
            if self.cfg.expt.reset_bias_after:
                soc.rfb_set_bias(bias_chan, float(self.cfg.expt.off_bias))

        heatmap_pumps, heatmap_dcs, heatmap_gain = self._make_heatmap_from_history(pump_pts, dc_pts, gain_pts)
        data = {
            "freq_mhz": freq,
            "xpts": freq,
            "baseline": copy.deepcopy(baseline),
            "baseline_amps": baseline_amps,
            "baseline_db": baseline_db,
            "pump_range": np.asarray(pump_range),
            "dc_range": np.asarray(dc_range),
            "measured_pump_gains": np.asarray(pump_pts),
            "measured_dc_biases_v": np.asarray(dc_pts),
            "measured_dc_biases_mv": 1e3 * np.asarray(dc_pts),
            "measured_gain_at_waste_db": np.asarray(gain_pts),
            "measured_cycle": np.asarray(cycle_pts),
            "measured_stage": np.asarray(stage_pts),
            "measured_gain_db": np.asarray(trace_gain_db),
            "measured_amps": np.asarray(trace_amps),
            "measured_phases": np.asarray(trace_phases),
            "dc_readback_v": np.asarray(dc_readback_v),
            "heatmap_pump_gains": heatmap_pumps,
            "heatmap_dc_biases_v": heatmap_dcs,
            "heatmap_dc_biases_mv": 1e3 * heatmap_dcs,
            "heatmap_gain_at_waste_db": heatmap_gain,
            "gain_window_mhz": float(self.cfg.expt.gain_window_mhz),
            "waste_freq_mhz": float(self.cfg.expt.waste_freq_mhz),
            "pump_freq_mhz": float(self.cfg.expt.pump_freq),
            "pump_mixer_freq_mhz": float(self.cfg.expt.pump_mixer_freq),
            "pump_ch": int(self.cfg.expt.pump_ch),
            "pump_attn1_db": float(self.cfg.expt.pump_attn1_db),
            "pump_attn2_db": float(self.cfg.expt.pump_attn2_db),
            "time": np.asarray(times),
        }
        self.data = data
        return data

    def analyze(self, data=None, **kwargs):
        if data is None:
            data = self.data

        ind = int(np.nanargmax(data["measured_gain_at_waste_db"]))
        data["best_pump_gain"] = float(data["measured_pump_gains"][ind])
        data["best_dc_bias_v"] = float(data["measured_dc_biases_v"][ind])
        data["best_dc_bias_mv"] = 1e3 * data["best_dc_bias_v"]
        data["best_gain_db"] = float(data["measured_gain_at_waste_db"][ind])
        data["best_index"] = ind
        self.data = data
        if self.cfg.expt.pump_on_after:
            self._turn_on_best_pump(data["best_pump_gain"], data["best_dc_bias_v"])
        if should_update_yaml(self.cfg.expt):
            update_jpa_config(
                self.config_file,
                self.cfg.expt,
                data=data,
                verbose=bool(self.cfg.expt.rspec_update_verbose),
            )
        return data

    def display(self, data=None, **kwargs):
        if data is None:
            data = self.data

        fig, ax = plt.subplots(figsize=(7, 5))
        mesh = ax.pcolormesh(
            data["heatmap_dc_biases_mv"],
            data["heatmap_pump_gains"],
            data["heatmap_gain_at_waste_db"],
            shading="auto",
        )
        ax.scatter(
            data["measured_dc_biases_mv"],
            data["measured_pump_gains"],
            c="w",
            s=12,
            edgecolors="k",
            linewidths=0.3,
        )
        if "best_gain_db" in data:
            ax.plot(data["best_dc_bias_mv"], data["best_pump_gain"], "rx", ms=10, mew=2)
        ax.set_xlabel("JPA DC Bias (mV)")
        ax.set_ylabel("Pump DAC Gain")
        ax.set_title(f"Adaptive JPA tuning near {data['waste_freq_mhz']:.3f} MHz")
        fig.colorbar(mesh, ax=ax, label="Gain vs baseline (dB)")
        fig.tight_layout()
        plt.show()
        return fig, ax
